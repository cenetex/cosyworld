// Bundle the shared dialogue context for the Rust host. Unlike the rules
// engine this bundle is not versioned: rebuild it whenever its sources change.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const root = fileURLToPath(new URL("../../", import.meta.url));
const output = new URL(
  "../orchestrator-rust/src/card_shared/narrator.js",
  import.meta.url,
);
const result = await build({
  absWorkingDir: root,
  entryPoints: ["v2/card-game/shared-narrator-entry.mjs"],
  bundle: true,
  write: false,
  platform: "neutral",
  format: "iife",
  target: "es2022",
  legalComments: "none",
  banner: {
    js: "// Generated by v2/scripts/build-card-shared-narrator.mjs. Not a journal input.",
  },
});
const text = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8").catch(() => "")) !== text)
    throw new Error(
      "Rebuild the shared narrator with node v2/scripts/build-card-shared-narrator.mjs.",
    );
} else await writeFile(output, text);
