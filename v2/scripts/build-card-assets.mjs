// Builds the media hash map and the Rust module that embeds every public
// card-game file. Cargo runs `--rust-out <file>` from build.rs, so the Rust
// module is never committed and two branches that add assets cannot conflict.
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { publicAssets } from "../card-game/public-assets.mjs";

const manifestPath = new URL(
  "../card-game/media-manifest.json",
  import.meta.url,
);
const check = process.argv.includes("--check");
const rustOutIndex = process.argv.indexOf("--rust-out");
const rustOut = rustOutIndex > 0 ? process.argv[rustOutIndex + 1] : null;
if (rustOutIndex > 0 && !rustOut) throw new Error("--rust-out needs a path");
const hash = (body) => createHash("sha256").update(body).digest("hex");
const source = (file) => new URL(`../card-game/${file}`, import.meta.url);
function assetBytes(asset) {
  const bytes = readFileSync(source(asset.source || asset.file));
  const offset = asset.offset || 0;
  if (!Number.isSafeInteger(offset) || offset < 0 || offset > bytes.length)
    throw new Error(`Invalid source offset for ${asset.file}`);
  if (asset.sourceHash && hash(bytes) !== asset.sourceHash)
    throw new Error(
      `Music source changed: ${asset.source}. Run npm run v2:card:music:build.`,
    );
  if (
    asset.source &&
    !publicAssets.some((entry) => entry.file === asset.source && !entry.source)
  )
    throw new Error(`Publish the original source for ${asset.file}`);
  return bytes.subarray(offset);
}
const media = Object.fromEntries(
  publicAssets
    .filter(({ contentType }) => /^(image|audio)\//.test(contentType))
    .map((asset) => [asset.file, hash(assetBytes(asset))]),
);
const manifest = `${JSON.stringify(media, null, 2)}\n`;
if (check || rustOut) {
  if (readFileSync(manifestPath, "utf8") !== manifest)
    throw new Error(
      "Card media hashes changed. Run npm run v2:card:assets:build.",
    );
} else writeFileSync(manifestPath, manifest);
const assets = publicAssets.map((asset) => ({
  ...asset,
  hash: hash(assetBytes(asset)),
}));
const identity = hash(JSON.stringify(assets.map(({ file, hash }) => [file, hash])));

const embed = (file) =>
  `include_bytes!(concat!(env!("CARGO_MANIFEST_DIR"), "/../card-game/${file}"))`;
const render = () => `// Embedded public card-game files.
// Generated by v2/scripts/build-card-assets.mjs from public-assets.mjs.

pub fn manifest_sha256() -> &'static str {
    "${identity}"
}

#[inline(never)]
pub fn get(path: &str) -> Option<(&'static str, &'static [u8])> {
    let asset: (&str, &[u8]) = match path {
${assets
  .map(({ file, contentType, source, offset = 0 }) =>
    source
      ? `        "${file}" => {
            let (_, bytes) = get("${source}")?;
            ("${contentType}", &bytes[${offset}..])
        }`
      : `        "${file}" => (
            "${contentType}",
            ${embed(file)},
        ),`,
  )
  .join("\n")}
        _ => return None,
    };
    Some(asset)
}

#[inline(never)]
pub fn etag(path: &str) -> Option<&'static str> {
    Some(match path {
${assets
  .map(({ file, hash }) => {
    const value = JSON.stringify('"' + hash + '"');
    const line = `        ${JSON.stringify(file)} => ${value},`;
    return line.length <= 100
      ? line
      : `        ${JSON.stringify(file)} => {
            ${value}
        }`;
  })
  .join("\n")}
        _ => return None,
    })
}
`;
const output = render();
if (rustOut) writeFileSync(rustOut, output);
console.log(
  `Card assets ${identity}: ${publicAssets.length} files${rustOut ? ` -> ${rustOut}` : ""}.`,
);
