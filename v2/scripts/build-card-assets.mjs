import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { publicAssets } from "../card-game/public-assets.mjs";

const destination = new URL(
  "../orchestrator-rust/src/card_assets.rs",
  import.meta.url,
);
const manifestPath = new URL(
  "../card-game/media-manifest.json",
  import.meta.url,
);
const check = process.argv.includes("--check");
const hash = (body) => createHash("sha256").update(body).digest("hex");
const source = (file) => new URL(`../card-game/${file}`, import.meta.url);
const media = Object.fromEntries(
  publicAssets
    .filter(({ contentType }) => /^(image|audio)\//.test(contentType))
    .map(({ file }) => [file, hash(readFileSync(source(file)))]),
);
const manifest = `${JSON.stringify(media, null, 2)}\n`;
if (check) {
  if (readFileSync(manifestPath, "utf8") !== manifest)
    throw new Error(
      "Card media hashes changed. Run npm run v2:card:assets:build.",
    );
} else writeFileSync(manifestPath, manifest);
const assets = publicAssets.map((asset) => ({
  ...asset,
  hash: hash(readFileSync(source(asset.file))),
}));

const output = `//! Embedded public card-game files.
//! Generated by v2/scripts/build-card-assets.mjs from public-assets.mjs.

#[inline(never)]
pub fn get(path: &str) -> Option<(&'static str, &'static [u8])> {
    let asset: (&str, &[u8]) = match path {
${assets
  .map(
    ({ file, contentType }) => `        "${file}" => (
            "${contentType}",
            include_bytes!("../../card-game/${file}"),
        ),`,
  )
  .join("\n")}
        _ => return None,
    };
    Some(asset)
}

#[inline(never)]
pub fn etag(path: &str) -> Option<&'static str> {
    Some(match path {
${assets
  .map(({ file, hash }) => {
    const value = JSON.stringify('"' + hash + '"');
    const line = `        ${JSON.stringify(file)} => ${value},`;
    return line.length <= 100
      ? line
      : `        ${JSON.stringify(file)} => {
            ${value}
        }`;
  })
  .join("\n")}
        _ => return None,
    })
}
`;
if (check) {
  if (readFileSync(destination, "utf8") !== output)
    throw new Error(
      "Card assets changed. Run npm run v2:card:assets:build and commit card_assets.rs.",
    );
  console.log(`Rust card assets are current: ${publicAssets.length} files.`);
} else {
  writeFileSync(destination, output);
  console.log(`Built Rust card assets: ${publicAssets.length} files.`);
}
