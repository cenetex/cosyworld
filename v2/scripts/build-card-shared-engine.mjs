// Bundle the same authored rules used by the browser for the bounded C host.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { sharedContentInput } from "./shared-content-input.mjs";
const root = fileURLToPath(new URL("../../", import.meta.url));
const output = new URL(
  "../orchestrator-rust/src/card_shared/engine-v78.js",
  import.meta.url,
);
const result = await build({
  absWorkingDir: root,
  entryPoints: ["v2/card-game/shared-world-entry.mjs"],
  bundle: true,
  write: false,
  platform: "neutral",
  format: "iife",
  target: "es2022",
  legalComments: "none",
  plugins: [sharedContentInput(root)],
  banner: {
    js: "// Generated by v2/scripts/build-card-shared-engine.mjs. Versioned server rules.",
  },
});
const text = result.outputFiles[0].text;
if (process.argv.includes("--check")) {
  if ((await readFile(output, "utf8")) !== text)
    throw new Error(
      "Rebuild the shared card rules with node v2/scripts/build-card-shared-engine.mjs.",
    );
} else await writeFile(output, text);
