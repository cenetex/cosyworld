#!/usr/bin/env node
// Draw each mounted card pack as a level map: where the places and ways are,
// what shuts each way, and what each gate needs done first.
//
//   node scripts/build-level-maps.mjs          # write docs/maps/
//   node scripts/build-level-maps.mjs --check  # fail if docs/maps/ is stale
//
// Reads the compiled card packs (v2/card-game/packs.json, built from
// v2/content/<pack>/card-world.json and v2/worlds/<pack>/card-bridge.json) and
// the hub names in forest.json. Writes, for every mounted pack,
// docs/maps/<pack>.md (Mermaid maps and tables) and docs/maps/<pack>.graph.json
// (the same graphs as data), plus docs/maps/index.md. Output has stable order
// and no dates, so regenerating changes nothing unless the packs changed.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildPackGraph, nameLookup } from "./lib/level-graph.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = "docs/maps";
const MARK = "<!-- Generated by scripts/build-level-maps.mjs. Do not edit. -->";
// A pack with more places than this is drawn one district at a time.
export const WHOLE_PACK_PLACES = 14;
const LABEL = 56;

const read = (file) => JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));
const clip = (text, max) => (text.length > max ? `${text.slice(0, max - 1)}…` : text);
const cell = (text) => String(text).replace(/\|/gu, "\\|").replace(/\n/gu, " ");
const code = (text) => `\`${text}\``;
const mid = (id) => `n_${id.replace(/[^A-Za-z0-9]/gu, "_")}`;
// A Mermaid label in quotes with the characters that break it removed.
const quoted = (text, max = LABEL) =>
  `"${clip(String(text), max).replace(/["#<>&`|\\]/gu, "'").replace(/[[\]{}]/gu, "(")}"`;

// --- Place maps ---------------------------------------------------------

const SHAPES = {
  road: (id, name) => `${id}{{${quoted(name)}}}`,
  ship: (id, name) => `${id}[[${quoted(name)}]]`,
  hub: (id, name) => `${id}((${quoted(name)}))`,
  external: (id, name) => `${id}([${quoted(name)}])`,
  place: (id, name) => `${id}[${quoted(name)}]`,
};

function drawEdges(edges, wordsOf) {
  // A pair of opposite ways with the same gate is one two-way line.
  const key = (e) => `${e.kind}|${e.gate || ""}|${e.transport || ""}`;
  const lines = [];
  const done = new Set();
  for (const e of edges) {
    const tag = `${e.from}>${e.to}|${key(e)}`;
    if (done.has(tag)) continue;
    done.add(tag);
    const back = edges.find(
      (o) => o.from === e.to && o.to === e.from && key(o) === key(e) && !e.oneWay && !o.oneWay,
    );
    if (back) done.add(`${back.from}>${back.to}|${key(back)}`);
    const [a, b] = [mid(e.from), mid(e.to)];
    const words = e.gate ? wordsOf(e.gate) : "";
    const verb = e.kind === "lane" ? "sail" : e.kind === "crossing" ? "cross" : "";
    const label = [verb, words].filter(Boolean).join(": ");
    if (e.gate) lines.push(`  ${a} ${back ? "<" : ""}-. ${quoted(label)} .-> ${b}`);
    else if (label) lines.push(`  ${a} ${back ? "<" : ""}-- ${quoted(label)} --> ${b}`);
    else lines.push(`  ${a} ${back ? "---" : "-->"} ${b}`);
  }
  return lines;
}

function placeMap(graph, scope, title) {
  const byId = new Map(graph.space.nodes.map((n) => [n.id, n]));
  const inside = new Set(scope);
  const edges = graph.space.edges.filter((e) => inside.has(e.from) || inside.has(e.to));
  const stubs = new Set(edges.flatMap((e) => [e.from, e.to]).filter((id) => !inside.has(id)));
  const gateWords = new Map(
    [...graph.mission.gates].map((g) => [g.id, g.words || (g.seal ? "sealed" : "")]),
  );
  const out = ["```mermaid", "flowchart LR", `  %% ${title}`];
  for (const id of [...inside].sort())
    out.push(`  ${SHAPES[byId.get(id).kind](mid(id), byId.get(id).name)}`);
  for (const id of [...stubs].sort()) {
    const n = byId.get(id);
    out.push(`  ${SHAPES[n.kind === "place" ? "external" : n.kind](mid(id), n.name)}`);
  }
  out.push(...drawEdges(edges, (g) => gateWords.get(g) || ""));
  if (stubs.size) out.push(`  classDef stub stroke-dasharray: 4 3`, `  class ${[...stubs].sort().map(mid).join(",")} stub`);
  out.push("```");
  return out.join("\n");
}

// Districts drawn as single boxes, joined through roads, the ship and other
// packs.
function overview(graph) {
  const byId = new Map(graph.space.nodes.map((n) => [n.id, n]));
  const rep = (id) => byId.get(id)?.district || id;
  const gateWords = new Map(graph.mission.gates.map((g) => [g.id, g.words || "sealed"]));
  const seen = new Set();
  const edges = [];
  for (const e of graph.space.edges) {
    const [from, to] = [rep(e.from), rep(e.to)];
    const tag = `${from}>${to}|${e.gate || ""}`;
    if (from === to || seen.has(tag)) continue;
    seen.add(tag);
    edges.push({ ...e, from, to });
  }
  const names = new Map(graph.space.districts.map((d) => [d.id, `${d.name} (${d.places.length})`]));
  const ids = new Set(edges.flatMap((e) => [e.from, e.to]));
  const out = ["```mermaid", "flowchart LR"];
  for (const id of [...ids].sort()) {
    const n = byId.get(id);
    out.push(
      `  ${n ? SHAPES[n.kind === "place" ? "external" : n.kind](mid(id), n.name) : `${mid(id)}[${quoted(names.get(id) || id)}]`}`,
    );
  }
  out.push(...drawEdges(edges, (g) => gateWords.get(g) || ""));
  out.push("```");
  return out.join("\n");
}

// --- Dependency charts --------------------------------------------------

const TYPE_SHAPE = {
  flag: (id, t) => `${id}(${quoted(t)})`,
  choice: (id, t) => `${id}(${quoted(t)})`,
  item: (id, t) => `${id}([${quoted(t)}])`,
  act: (id, t) => `${id}[${quoted(t)}]`,
  want: (id, t) => `${id}[${quoted(t)}]`,
  topic: (id, t) => `${id}[${quoted(t)}]`,
  resident: (id, t) => `${id}>${quoted(t)}]`,
  place: (id, t) => `${id}{{${quoted(t)}}}`,
  route: (id, t) => `${id}{{${quoted(t)}}}`,
  lane: (id, t) => `${id}{{${quoted(t)}}}`,
  crossing: (id, t) => `${id}{{${quoted(t)}}}`,
};
const GATE_TYPES = ["route", "lane", "crossing", "place"];

// What a node is called in a chart.
function titleOf(graph, id) {
  const type = id.slice(0, id.indexOf(":"));
  const rest = id.slice(type.length + 1);
  const known = [...graph.mission.gates, ...graph.mission.acts].find((g) => g.id === id);
  if (known && type !== "item" && type !== "resident") return known.title;
  const name = graph.space.nodes.find((n) => n.id === rest)?.name;
  const item = graph.mission.items.find((i) => i.id === rest)?.name;
  const prefix = `${graph.pack.split("-")[0]}-`;
  return name || item || known?.title || (rest.startsWith(prefix) ? rest.slice(prefix.length) : rest);
}

// The chain behind a set of gates, as a chart: arrows point from what is
// needed to what it opens.
function dependencyChart(graph, starts) {
  const needs = graph.mission.needs;
  const gated = new Set([...graph.mission.gates, ...graph.mission.acts].map((g) => g.id));
  const shown = (id) => {
    const type = id.slice(0, id.indexOf(":"));
    return !["resident", "place"].includes(type) || gated.has(id);
  };
  const seen = new Set(starts);
  const stack = [...starts];
  const links = [];
  while (stack.length) {
    const id = stack.pop();
    for (const need of (needs[id] || []).filter(shown)) {
      links.push([need, id]);
      if (!seen.has(need)) {
        seen.add(need);
        stack.push(need);
      }
    }
  }
  const out = ["```mermaid", "flowchart TD"];
  for (const id of [...seen].sort()) {
    const type = id.slice(0, id.indexOf(":"));
    out.push(`  ${(TYPE_SHAPE[type] || TYPE_SHAPE.act)(mid(id), titleOf(graph, id))}`);
  }
  for (const [a, b] of links.sort((x, y) => `${x}`.localeCompare(`${y}`)))
    out.push(`  ${mid(a)} --> ${mid(b)}`);
  const gateIds = [...seen].filter((id) => GATE_TYPES.includes(id.slice(0, id.indexOf(":"))));
  out.push("  classDef gate fill:#fdd,stroke:#a33");
  if (gateIds.length) out.push(`  class ${gateIds.sort().map(mid).join(",")} gate`);
  out.push("```");
  return { text: out.join("\n"), count: seen.size };
}

// --- Tables -------------------------------------------------------------

const GROUP_ORDER = ["flag", "choice", "item", "act", "resident", "place", "topic", "want", "route", "lane", "crossing"];
const PLURAL = { flag: "flags", choice: "choices", item: "items", act: "acts", resident: "residents", place: "places", topic: "topics", want: "wants", route: "routes", lane: "lanes", crossing: "crossings" };

function prerequisites(p) {
  const parts = GROUP_ORDER.filter((t) => p[t]?.length).map(
    (t) => `${PLURAL[t]}: ${p[t].map(code).join(", ")}`,
  );
  return parts.length ? parts.join("<br>") : "none";
}

function gateTable(graph) {
  const rows = ["| Gate | Direct condition | Transitive prerequisites | Latch (kept once made) and live (read now) |", "| --- | --- | --- | --- |"];
  for (const g of graph.mission.gates) {
    const named = (keys) => keys.map((k) => graph.atoms[k].words).join("; ");
    const how = [
      g.latch.length ? `latch: ${named(g.latch)}` : "",
      g.live.length ? `live: ${named(g.live)}` : "",
      g.follows ? `route ${g.follows === "latches" ? "latches open once opened" : "follows its condition"}` : "",
      g.seal ? `sealed (${g.seal.kind}${g.seal.target ? ` ${g.seal.target}` : ""})` : "",
    ].filter(Boolean);
    rows.push(
      `| ${code(g.id)}<br>${cell(g.title)} | ${cell(g.ids || "always shut until sealed lock opens")} | ${cell(prerequisites(g.prerequisites))} | ${cell(how.join("<br>") || "none")} |`,
    );
  }
  return rows.join("\n");
}

function flagTable(graph) {
  const rows = ["| Flag | Kind | Set by | Read directly by | Gates behind it, transitively | Acts behind it |", "| --- | --- | --- | --- | --- | --- |"];
  const list = Object.entries(graph.mission.flags).filter(([, f]) => f.gates.length || f.acts.length);
  list.sort(([a, x], [b, y]) => y.gates.length - x.gates.length || a.localeCompare(b));
  for (const [key, f] of list) {
    const ids = (xs) => (xs.length ? xs.map(code).join(", ") : "none");
    rows.push(
      `| ${code(key)} | ${f.kind} | ${cell(ids(f.setBy))} | ${f.readBy.length} | ${cell(ids(f.gates))} | ${f.acts.length} |`,
    );
  }
  return rows.join("\n");
}

// --- Pages --------------------------------------------------------------

export function renderPackPage(graph) {
  const { space, mission } = graph;
  const live = space.nodes.filter((n) => n.kind === "place" || n.kind === "road" || n.kind === "ship");
  const spaceGates = new Set(["route", "lane", "crossing", "place"]);
  const lines = [
    MARK,
    `# Level map: ${graph.name}`,
    "",
    `Pack ${code(graph.pack)}, revision ${graph.revision}. Entry ${code(graph.entry)}. Part of the [level maps](index.md); data in [${graph.pack}.graph.json](${graph.pack}.graph.json). Built from ${code(`v2/content/${graph.pack}/card-world.json`)} and ${code(`v2/worlds/${graph.pack}/card-bridge.json`)}.`,
    "",
    `${live.length} places, ${space.edges.length} ways, ${mission.gates.length} gates, ${mission.acts.length} acts, ${Object.keys(mission.flags).length} flags, ${space.districts.length} district${space.districts.length === 1 ? "" : "s"}.`,
    "",
    "How to read the maps: a solid line is an open way and a dashed line is a gated way, labelled with its condition in plain words. A hexagon is a road, a double box is the ship, a round node is another world, a dashed outline is a place beyond this map. In the dependency charts an arrow points from what is needed to what it opens; red is a gate. A condition under `any` is a set of alternatives, and the charts and the prerequisite lists include all of them.",
    "",
    "## Place map",
    "",
  ];
  const whole = live.filter((n) => n.kind === "place").length <= WHOLE_PACK_PLACES;
  if (whole) lines.push(placeMap(graph, live.map((n) => n.id), graph.name), "");
  else {
    lines.push("The districts and the roads between them.", "", overview(graph), "");
    for (const d of space.districts)
      lines.push(`### ${d.name}`, "", `Places: ${d.places.map(code).join(", ")}.`, "", placeMap(graph, d.places, d.name), "");
  }
  lines.push("## Dependency chart", "");
  const inScope = (g, places) =>
    graph.space.edges.some((e) => e.gate === g.id && (places.includes(e.from) || places.includes(e.to)));
  const charts = whole
    ? [["", graph.space.nodes.map((n) => n.id)]]
    : space.districts.map((d) => [d.name, d.places]);
  let drawn = 0;
  for (const [name, places] of charts) {
    const starts = mission.gates.filter((g) => spaceGates.has(g.kind) && inScope(g, places)).map((g) => g.id);
    if (!starts.length) continue;
    const chart = dependencyChart(graph, starts);
    drawn += 1;
    lines.push(name ? `### ${name}` : "", "", `${starts.length} gated way${starts.length === 1 ? "" : "s"} here; ${chart.count} nodes in the chain.`, "", chart.text, "");
  }
  if (!drawn) lines.push("This pack has no gated ways.", "");
  lines.push("## Gates", "", "Every condition that shuts a way, a place, a resident or a thing. The prerequisites are everything reachable through the condition, over every alternative, and so can list more than one route needs.", "", gateTable(graph), "");
  lines.push("## Flags", "", "Flags that gate something, most-depended-on first. A latch flag is only ever set; a toggle flag is also cleared by some act. \"Gates behind it\" are all gates whose prerequisites include the flag, directly or through other flags and acts.", "", flagTable(graph), "");
  if (space.retired.length) lines.push("## Retired ways", "", space.retired.map(code).join(", "), "");
  return `${lines.join("\n").replace(/\n{3,}/gu, "\n\n")}\n`;
}

export function renderIndex(graphs, hub) {
  const lines = [
    MARK,
    "# Level maps",
    "",
    "Maps of every mounted card pack: the places and ways, the gates that shut them, and what each gate needs done first. They are built from the pack data by `scripts/build-level-maps.mjs` and rebuilt by `npm run regen`; `npm run regen:check` fails when they are stale. Do not edit them by hand. Read [the current game source map](../current-game.md) for the data's owners.",
    "",
    "| Pack | Places | Ways | Gates | Acts | Flags | Districts |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...graphs.map((g) => {
      const places = g.space.nodes.filter((n) => n.kind !== "hub" && n.kind !== "external").length;
      return `| [${cell(g.name)}](${g.pack}.md) | ${places} | ${g.space.edges.length} | ${g.mission.gates.length} | ${g.mission.acts.length} | ${Object.keys(g.mission.flags).length} | ${g.space.districts.length} |`;
    }),
    "",
    "## How the packs join",
    "",
    "```mermaid",
    "flowchart LR",
    `  hub((${quoted("The hub")}))`,
    ...graphs.map((g) => `  ${mid(g.pack)}[${quoted(g.name)}]`),
    ...graphs.flatMap((g) =>
      g.entries.map(
        (e) => `  ${mid(e.joins === "hub" ? "hub" : e.joins)} -- ${quoted(`${e.at} to ${e.arrive}`)} --> ${mid(g.pack)}`,
      ),
    ),
    "```",
    "",
    `The hub starts at ${code(hub.start)}. Entries come from each pack's bridge.`,
    "",
    "## Condition kinds seen",
    "",
    ...graphs.map((g) => `- ${g.name}: ${g.conditionKinds.map(code).join(", ") || "none"}`),
    "",
  ];
  return `${lines.join("\n")}`;
}

// Everything the build writes, as { path: text }.
export function buildAll() {
  const table = read("v2/card-game/packs.json");
  const nameOf = nameLookup(table.packs, read("v2/card-game/forest.json"));
  const graphs = table.packs.map((pack) => buildPackGraph(pack, table.hub, nameOf));
  const files = {};
  for (const graph of graphs) {
    files[`${OUT}/${graph.pack}.md`] = renderPackPage(graph);
    files[`${OUT}/${graph.pack}.graph.json`] = `${JSON.stringify(graph, null, 2)}\n`;
  }
  files[`${OUT}/index.md`] = renderIndex(graphs, table.hub);
  return files;
}

// Files in docs/maps that this build made and no longer makes.
function staleFiles(files) {
  const dir = path.join(root, OUT);
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir)
    .map((name) => `${OUT}/${name}`)
    .filter((file) => !(file in files))
    .filter((file) => file.endsWith(".graph.json") || fs.readFileSync(path.join(root, file), "utf8").startsWith(MARK));
}

function main(argv) {
  const files = buildAll();
  const stale = staleFiles(files);
  if (argv.includes("--check")) {
    const wrong = Object.entries(files)
      .filter(([file, text]) => !fs.existsSync(path.join(root, file)) || fs.readFileSync(path.join(root, file), "utf8") !== text)
      .map(([file]) => file)
      .concat(stale);
    if (wrong.length) {
      console.error(`Level maps are stale: ${wrong.join(", ")}. Run npm run regen.`);
      process.exitCode = 1;
      return;
    }
    console.log(`Level maps are current: ${Object.keys(files).length} files.`);
    return;
  }
  fs.mkdirSync(path.join(root, OUT), { recursive: true });
  for (const [file, text] of Object.entries(files)) fs.writeFileSync(path.join(root, file), text);
  for (const file of stale) fs.rmSync(path.join(root, file));
  console.log(`Wrote ${Object.keys(files).length} level map files to ${OUT}/.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv.slice(2));
